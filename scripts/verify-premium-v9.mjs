import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const postcss = require("postcss");
import { SITE_THEMES } from "../src/lib/themes.js";
const read=p=>fs.readFileSync(p,"utf8");
const issues=[];
const check=(condition,message)=>{if(!condition)issues.push(message)};
const css=read('src/app/premium-v9.css');
const elements=read('src/components/site/Elements.jsx');
const hero=read('src/components/site/Hero.jsx');
const header=read('src/components/site/SiteHeader.jsx');
const footer=read('src/components/site/SiteFooter.jsx');
const layout=read('src/app/layout.jsx');
const brand=read('src/components/site/BrandMark.jsx');
try { postcss.parse(css,{from:'src/app/premium-v9.css'}); } catch(e) { issues.push(`Invalid CSS: ${e.message}`); }
check(SITE_THEMES.length===10, 'All 10 preexisting theme presets must remain available');
check(layout.includes('premium-v9.css'), 'New global design layer not imported');
check(elements.includes('v9-page-banner') && elements.includes('v9-banner-photo'), 'Full-bleed common PageBanner missing');
check(!elements.slice(elements.indexOf('export function PageBanner('),elements.indexOf('export function BreadcrumbSide(')).includes('md:grid-cols'), 'PageBanner is still split into two columns');
check(hero.includes('v9-home-photo') && hero.includes('v9-home-stage'), 'Home slideshow not image-backed');
check(hero.includes('who-we-are') && hero.includes('v9-home-stats'), 'Who We Are / hero highlights missing');
check(css.includes('height: 70svh') && css.includes('object-fit: cover'), 'Full width 70svh banner styles missing');
check(!css.includes('background-image: linear-gradient('), 'Image overlay gradients must not be applied to banners');
check(css.includes('.v9-page-content') && css.includes('rgba(255,255,255,.9)'), 'Readable text-only translucent panel missing');
check(header.includes('BrandMark') && footer.includes('BrandMark') && brand.includes('<svg'), 'Shared vector brand missing');
check(header.includes('v9-mega-item') && css.includes('a.v9-mega-item:hover'), 'Practice-area hover background is missing');
check(header.includes('v9-mobile-drawer') && header.includes('"Escape"'), 'Mobile sliding menu keyboard interaction missing');
check(css.includes('v9-footer-link:hover') && css.includes('v9-topbar'), 'Theme-linked header/footer styling missing');
check(css.includes('prefers-reduced-motion'), 'Reduced-motion accessibility rule missing');
check(!fs.existsSync('.env.local'), 'A credential-bearing .env.local was included');
const pageFiles=[];
const walk=(dir)=>{for(const e of fs.readdirSync(dir,{withFileTypes:true})){const n=path.join(dir,e.name);if(e.isDirectory())walk(n);else if(e.name==='page.jsx')pageFiles.push(n)}};
walk('src/app/(site)');
const banners=pageFiles.filter(p=>read(p).includes('<PageBanner')).length;
check(banners>=15, `Unexpectedly few PageBanner consumers: ${banners}`);
console.log(JSON.stringify({status:issues.length?'FAIL':'PASS', singleAccentThemes:SITE_THEMES.length, pagesUsingFullBleedBanner:banners, photoOverlay:'none', heroHeight:'70svh', sharedBrand:true, issues},null,2));
if(issues.length)process.exit(1);
