import { SITE_THEMES, DEFAULT_THEME } from "../src/lib/themes.js";
import { writeFileSync } from "node:fs";
const css = [
  `/* AUTO GENERATED by npm run themes:css — edit src/lib/themes.js. */`,
  `:root {color-scheme:light;}`,
];
for (const t of SITE_THEMES) {
  const selector =
    t.id === DEFAULT_THEME
      ? `:root,html[data-theme="${t.id}"]`
      : `html[data-theme="${t.id}"]`;
  css.push(
    `${selector}{\n${[
      ["theme-dark", t.dark],
      ["theme-ink", t.ink],
      ["theme-primary", t.primary],
      ["theme-accent", t.accent],
      ["theme-alt", t.alt],
      ["theme-surface", t.surface],
      ["theme-tint", t.tint],
      ["theme-border", t.border],
      ["theme-muted", "#616B78"],
      ["theme-on-primary", "#FFFFFF"],
      ["theme-on-dark", "#FFFFFF"],
      ["theme-on-accent", "#FFFFFF"],
      ["theme-card", "transparent"],
      ["theme-white", "#FFFFFF"],
      ["theme-gradient", `linear-gradient(115deg,color-mix(in srgb,${t.primary} 86%,#18202C),${t.primary},color-mix(in srgb,${t.primary} 86%,white))`],
      ["theme-accent-light", t.primary],
      ["theme-primary-light", t.primary],
      [
        "theme-dark-rgb",
        t.dark
          .match(/\w\w/g)
          .slice(0, 3)
          .map((x) => parseInt(x, 16))
          .join(", "),
      ],
    ]
      .map(([key, value]) => `  --${key}:${value};`)
      .join("\n")}\n}`,
  );
}
writeFileSync("src/app/themes.generated.css", css.join("\n\n") + "\n");
console.log(`Generated ${SITE_THEMES.length} themes`);
